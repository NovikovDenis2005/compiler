package vm;

import java.util.List;

/**
 * Скомпилированная функция: имя, список параметров и собственный байт-код.
 *
 * Каждая функция компилируется в отдельный список инструкций (а не в общий
 * массив со смещениями) — так проще и нагляднее. При вызове машина создаёт
 * новый кадр с этим кодом; адреса прыжков внутри функции локальны для неё.
 */
public record SimpleVmFunction(String name, List<String> params, List<SimpleVmInstruction> code) {
}
